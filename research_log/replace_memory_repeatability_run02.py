    new_meta = read(publication / "run_02/metadata.json")
    summary_text = json.dumps({k: new_meta[k] for k in ("run_status", "repeat_count", "failed_repeat_count", "run_id")}) + "\n"
    (publication / "run_02_stdout.txt").write_text(summary_text, encoding="utf-8")
    (publication / "run_02_stderr.txt").write_text("", encoding="utf-8")
    save(publication / "operator_context_run_02.json", read(session / "preflight.json"))
    save(publication / "operator_events_run_02.json", dict(execution_amendment=AMENDMENT,
         report_scope="Observed snapshots, no new user activity confirmation", observations=record["observations"]))
