def require(condition, message):
    if not condition:
        raise ValueError(message)


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def tree_hashes(directory):
    return {p.relative_to(directory).as_posix(): digest(p)
            for p in sorted(directory.rglob("*")) if p.is_file() and p.name != LOCK}


def save(path, value):
    r._save_metadata(path, value)


def read(path):
    return r._read_json(path)


def csv_rows(path):
    with path.open(encoding="utf-8", newline="") as stream:
        return list(csv.DictReader(stream))


def within_results(path):
    path = Path(path).resolve()
    require(path.is_relative_to((ROOT / "data/results").resolve())
            and path != (ROOT / "data/results").resolve(), "Path must be inside project data/results")
    return path


def archive(study, destination):
    before = tree_hashes(study)
    shutil.copytree(study, destination, ignore=shutil.ignore_patterns(LOCK))
    require(tree_hashes(destination) == before == tree_hashes(study), "Archive hash mismatch")
    return before


@contextmanager
def awake(state_api=None):
    if state_api is None:
        state_api = ctypes.WinDLL("kernel32", use_last_error=True).SetThreadExecutionState
        state_api.argtypes, state_api.restype = (wintypes.DWORD,), wintypes.DWORD
    previous = state_api(0x80000001)
    require(previous != 0, "Could not request idle sleep inhibition")
    record = dict(api="SetThreadExecutionState", requested_flags=0x80000001,
                  previous_flags=int(previous), acquired_at_utc=r.common._now(),
                  limitation="Manual sleep and lid closure are not prevented", restored=False)
    try:
        yield record
    finally:
        record["restored"] = bool(state_api(0x80000000 | int(previous)))
        record["released_at_utc"] = r.common._now()
        require(record["restored"], "Could not restore thread execution state")


def powershell_json(script):
    completed = subprocess.run(["powershell.exe", "-NoProfile", "-NonInteractive", "-Command",
                                "[Console]::OutputEncoding = [System.Text.Encoding]::UTF8; " + script],
                               capture_output=True, check=True, encoding="utf-8", timeout=45)
    require(not completed.stderr.strip(), "PowerShell observation stderr: " + completed.stderr)
    return json.loads(completed.stdout) if completed.stdout.strip() else None


def observe():
    class Power(ctypes.Structure):
        _fields_ = [("ac", wintypes.BYTE), ("battery_flag", wintypes.BYTE),
                    ("battery_percent", wintypes.BYTE), ("system_status", wintypes.BYTE),
                    ("battery_life", wintypes.DWORD), ("battery_full_life", wintypes.DWORD)]
    power = Power()
    api = ctypes.WinDLL("kernel32", use_last_error=True).GetSystemPowerStatus
    api.argtypes, api.restype = (ctypes.POINTER(Power),), wintypes.BOOL
    require(bool(api(ctypes.byref(power))), "Cannot observe power status")
    info = powershell_json("$ErrorActionPreference='Stop'; [pscustomobject]@{ "
        "boot_at=(Get-CimInstance Win32_OperatingSystem).LastBootUpTime.ToUniversalTime().ToString('o'); "
        "python_processes=@(Get-CimInstance Win32_Process -Filter \"Name = 'python.exe' OR Name = 'pythonw.exe'\" "
        "| Select-Object ProcessId, ParentProcessId, Name, CommandLine) } | ConvertTo-Json -Depth 5")
    return dict(observed_at_utc=r.common._now(), ac_line_status=int(power.ac),
                battery_percent=int(power.battery_percent), **info,
                observation_scope="Point observations; user activity/updates not continuously certified")


def power_events(start, end):
    # Times are generated by our own aware datetime clock, never arbitrary shell text.
    start, end = datetime.fromisoformat(start).isoformat(), datetime.fromisoformat(end).isoformat()
    return powershell_json("$ErrorActionPreference='Stop'; $events=@(Get-WinEvent -FilterHashtable @{ "
        "LogName='System'; ProviderName=@('Microsoft-Windows-Kernel-Power','Microsoft-Windows-Power-Troubleshooter'); "
        f"StartTime=[datetime]'{start}'; EndTime=[datetime]'{end}' "
        "} -ErrorAction SilentlyContinue -ErrorVariable eventErrors); "
        "$bad=@($eventErrors | Where-Object { $_.FullyQualifiedErrorId -notlike 'NoMatchingEventsFound*' }); "
        "if ($bad.Count) { throw ($bad | Out-String) }; "
        "ConvertTo-Json -InputObject @($events | ForEach-Object { [pscustomobject]@{ "
        "time_created_utc=$_.TimeCreated.ToUniversalTime().ToString('o'); Id=$_.Id; "
        "ProviderName=$_.ProviderName; Message=$_.Message } }) -Depth 4") or []


def collect(study, output, plan, context, execution_git):
    """One fresh parent, original full Run 2 schedule, no measurement retries."""
    output.mkdir(exist_ok=False)
    metadata = {**r._metadata(plan), "run_id": 2, "git": execution_git,
        "execution_amendment": AMENDMENT, "execution_role": "replacement_of_logical_run_02_after_run_06",
        "measurement_code_commit": plan["implementation_commit"], "operator_observations": context,
        "planned_memory_repeat_count": len(plan["expected_keys"]["memory"]),
        "planned_timing_repeat_count": len(plan["expected_keys"]["timing"]),
        "memory_repeat_count": 0, "timing_repeat_count": 0, "job_count": 0, "repeat_status_counts": {}}
    artifacts, memory_rows, timing_rows = [], [], []
    immutable = {n: (study / n, digest(study / n)) for n in ("plan.json", "samples.csv", ".gitattributes")}
    error = None
    try:
        save(output / "metadata.json", metadata)
        require(r._sources() == plan["source_sha256"], "Frozen measurement sources changed")
        require(r._same(r._check_config(), plan["config"]), "Configuration changed")
        samples = r._saved_samples(study / "samples.csv", plan["samples"])
        old_refs = {(v["sample_id"], v["algorithm"]): v
                    for v in r._read_csv(study / "run_01/references.csv", r.REFERENCE_FIELDS)}
        with tempfile.TemporaryDirectory(prefix="replacement_run02_inputs_") as temporary:
            references = r._prepare(samples, Path(temporary), old_refs)
            ref_path = output / "references.csv"
            artifacts.append(ref_path)
            r._write_csv(ref_path, r.REFERENCE_FIELDS, (v for v, _ in references.values()))
            with ExitStack() as stack:
                writers = {}
                for kind, fields in (("memory", r.MEMORY_FIELDS), ("timing", r.TIMING_FIELDS)):
                    path = output / f"{kind}_repeats.csv"
                    artifacts.append(path)
                    stream = stack.enter_context(path.open("x", encoding="utf-8", newline=""))
                    writer = csv.DictWriter(stream, fieldnames=fields)
                    writer.writeheader()
                    stream.flush()
                    writers[kind] = writer, stream
                counts = Counter()
                for job in plan["schedules"]["2"]:
                    reference, paths = references[(job["sample_id"], job["algorithm"])]
                    require(reference["status"] == "ok", "Reference preparation failed; retain attempt")
                    request = {**reference, **job, "attempt_id": plan["attempt_id"]}
                    if job["kind"] == "memory":
                        compress = job["phase"] == "compress"
                        request.update(input_size=reference["original_size" if compress else "compressed_size"],
                            input_sha256=reference["original_sha256" if compress else "compressed_sha256"],
                            expected_output_sha256=reference["compressed_sha256" if compress else "original_sha256"])
                    rows = r._raw_rows(request, r.run_worker(request, paths))
                    writer, stream = writers[job["kind"]]
                    for row in rows:
                        writer.writerow(row)
                        stream.flush()
                        (memory_rows if job["kind"] == "memory" else timing_rows).append(row)
                        counts[row["status"]] += 1
                    metadata.update(job_count=metadata["job_count"] + 1,
                        memory_repeat_count=len(memory_rows), timing_repeat_count=len(timing_rows),
                        repeat_count=len(memory_rows) + len(timing_rows), repeat_status_counts=dict(counts),
                        failed_repeat_count=sum(v["status"] != "ok" or v["bundle_status"] != "ok"
                                                for v in memory_rows + timing_rows))
                    save(output / "metadata.json", metadata)
            for reference, paths in references.values():
                for phase, path in paths.items():
                    require(digest(path) == reference["original_sha256" if phase == "compress" else "compressed_sha256"],
                            "Prepared input changed")
            summary = output / "measurements.csv"
            artifacts.append(summary)
            r._write_csv(summary, r.MEASUREMENT_FIELDS, r.summarize(plan, 2, memory_rows, timing_rows))
        metadata["run_status"] = "completed_with_failures" if metadata["failed_repeat_count"] else "completed"
    except BaseException as exc:
        error = exc
        metadata.update(run_status="aborted", run_error=f"{type(exc).__name__}: {exc}")
        raise
    finally:
        r._finish(output / "metadata.json", metadata, artifacts, immutable, error)
    return metadata


def validate_saved(directory, plan, run_id):
    """Independent saved-value medians and schedule/identity checks; no codecs."""
    meta = read(directory / "metadata.json")
    require(meta["finalization_status"] == "completed" and not meta["finalization_errors"]
            and meta["provenance_unchanged"] is True and not meta["validity_issues"], "Run finalization/provenance failed")
    require(meta["measurement_status"] == "validation_only" and meta["score_inclusion"] is False,
            "Unexpected formal score inclusion")
    require(meta["source_sha256"] == meta["source_sha256_at_end"] == meta["planned_source_sha256"] == plan["source_sha256"],
            "Run measurement source mismatch")
    require(set(meta["artifact_sha256"]) == set(ARTIFACTS), "Incomplete artifact manifest")
    for name, expected in meta["artifact_sha256"].items():
        require(digest(directory / name) == expected, "Artifact hash mismatch: " + name)
    refs = csv_rows(directory / "references.csv")
    refmap = {(v["sample_id"], v["algorithm"]): v for v in refs}
    pairs = {(v["sample_id"], a) for v in plan["samples"] for a in r.ALGORITHMS}
    require(len(refs) == len(refmap) == len(pairs) and set(refmap) == pairs, "Reference pair matrix mismatch")
    groups, rawstats, failures = {}, {}, []
    for kind, metric in (("memory", "peak_process_working_set_bytes"), ("timing", "elapsed_ns")):
        rows = csv_rows(directory / f"{kind}_repeats.csv")
        expected = {tuple(key) for key in plan["expected_keys"][kind]}
        keys, grouped = set(), defaultdict(list)
        for row in rows:
            key = (row["sample_id"], row["algorithm"], row["phase"], int(row["repeat_index"]))
            require(key in expected and key not in keys, "Duplicate/unplanned raw key")
            keys.add(key)
            job = plan["schedules"][str(run_id)][int(row["schedule_index"])]
            require(row["run_id"] == str(run_id) and row["attempt_id"] == plan["attempt_id"]
                    and row["request_id"] == job["request_id"] and kind == job["kind"]
                    and key[:2] == (job["sample_id"], job["algorithm"]), "Raw schedule identity mismatch")
            if kind == "memory":
                require(key[2:] == (job["phase"], job["repeat_index"]), "Memory repeat schedule mismatch")
            ref = refmap[key[:2]]
            require(ref["status"] == "ok" and ref["reference_roundtrip_verified"] == "True", "Unverified reference")
            compress = key[2] == "compress"
            require(int(row["input_size"]) == int(ref["original_size" if compress else "compressed_size"])
                    and row["input_sha256"] == ref["original_sha256" if compress else "compressed_sha256"]
                    and row["expected_output_sha256"] == ref["compressed_sha256" if compress else "original_sha256"],
                    "Raw input/reference mismatch")
            valid = (row["status"] == row["bundle_status"] == "ok" and all(row[k] == "True" for k in
                     ("verified", "reference_roundtrip_verified", "input_verified_before", "input_verified_after")))
            if valid:
                require(row[metric].isdigit() and int(row[metric]) > 0 and row["return_code"] == "0"
                        and not row["error"] and not row["stderr"], "Invalid successful raw metric/exit")
                require(json.loads(row["subprocess_options"]) == r.OPTIONS, "Worker options mismatch")
                if kind == "timing":
                    require(row["timer"] == "time.perf_counter_ns"
                            and row["actual_output_sha256"] == row["expected_output_sha256"], "Timing verification mismatch")
                else:
                    require(row["measurement_method"] == r.common.METHOD, "Memory method mismatch")
            else:
                failures.append(dict(kind=kind, **row))
            grouped[key[:2]].append((row, valid))
        require(keys == expected and len(rows) == len(expected), "Incomplete repeat matrix")
        require(meta[kind + "_repeat_count"] == len(rows), "Metadata repeat count mismatch")
        groups[kind] = grouped
        rawstats[kind] = dict(rows=len(rows), status_counts=dict(Counter(v["status"] for v in rows)),
                             verified_counts=dict(Counter(v["verified"] for v in rows)))
    summaries = csv_rows(directory / "measurements.csv")
    require(len(summaries) == len(pairs) and {(v["sample_id"], v["algorithm"]) for v in summaries} == pairs,
            "Measurement pair matrix mismatch")
    for value in summaries:
        key = value["sample_id"], value["algorithm"]
        bad = sum(not valid for kind in groups for _, valid in groups[kind][key])
        require(int(value["failed_repeat_count"]) == bad and value["verified"] == str(bad == 0), "Pair failure mismatch")
        metrics = [n for n in r.MEASUREMENT_FIELDS if n not in ("sample_id", "algorithm", "verified", "failed_repeat_count")]
        if bad:
            require(all(value[n] == "" for n in metrics), "Failed pair has normal metrics")
            continue
        ref = refmap[key]
        expected_values = {"compression_ratio": int(ref["compressed_size"]) / int(ref["original_size"])}
        for phase in r.PHASES:
            prefix = "compression" if phase == "compress" else "decompression"
            for kind, metric, suffix, scale in (("memory", "peak_process_working_set_bytes", "_peak_memory_bytes", 1),
                                               ("timing", "elapsed_ns", "_time_ms", 1_000_000)):
                vals = [int(v[metric]) for v, _ in groups[kind][key] if v["phase"] == phase]
                expected_values[prefix + suffix] = statistics.median(vals) / scale
        expected_values["peak_memory_bytes"] = max(expected_values[n + "_peak_memory_bytes"] for n in ("compression", "decompression"))
        require(all(math.isfinite(float(value[n])) and math.isclose(float(value[n]), x, rel_tol=1e-12, abs_tol=1e-12)
                    for n, x in expected_values.items()), "Saved median/ratio differs from raw values")
    require(meta["job_count"] == len(plan["schedules"][str(run_id)]) and meta["failed_repeat_count"] == len(failures)
            and meta["repeat_count"] == sum(v["rows"] for v in rawstats.values()), "Run count mismatch")
    require(meta["run_status"] == ("completed_with_failures" if failures else "completed"), "Run status mismatch")
    return dict(run_id=run_id, run_status=meta["run_status"], job_count=meta["job_count"], raw=rawstats,
        pair_count=len(summaries), normal_pair_count=sum(v["verified"] == "True" for v in summaries),
        failed_pair_count=sum(v["verified"] != "True" for v in summaries), failed_repeat_count=len(failures),
        started_at_utc=meta["started_at_utc"], finished_at_utc=meta["finished_at_utc"],
        duration_seconds=(datetime.fromisoformat(meta["finished_at_utc"]) - datetime.fromisoformat(meta["started_at_utc"])).total_seconds(),
        preserved_failed_records=failures, record_integrity_checks_passed=True)


def publish_files(study, publication, session):
    """Archive exists already; retain displaced files and a recoverable transaction."""
    displaced = session / "displaced_active_files"
    displaced.mkdir(exist_ok=False)
    state = dict(status="installing", changes=[], started_at_utc=r.common._now())
    save(session / "installation.json", state)
    try:
        for prepared in sorted(publication.iterdir()):
            target = study / prepared.name
            backup = displaced / prepared.name
            record = dict(name=prepared.name, old_moved=False, new_installed=False)
            state["changes"].append(record)
            save(session / "installation.json", state)
            if target.exists():
                os.replace(target, backup)
                record["old_moved"] = True
                save(session / "installation.json", state)
            os.replace(prepared, target)
            record["new_installed"] = True
            save(session / "installation.json", state)
        state.update(status="installed", finished_at_utc=r.common._now())
        save(session / "installation.json", state)
    except BaseException:
        # Never delete either version, even during rollback.
        recovered = session / "rolled_back_new_files"
        recovered.mkdir(exist_ok=True)
        for entry in reversed(state["changes"]):
            target, backup = study / entry["name"], displaced / entry["name"]
            if entry["new_installed"]:
                os.replace(target, recovered / entry["name"])
            if entry["old_moved"]:
                os.replace(backup, target)
        state["status"] = "rolled_back"
        save(session / "installation.json", state)
        raise


