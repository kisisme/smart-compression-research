            "Run 2의 memory·timing 전체를 재측정해 활성 경로에 교체했다. 나머지 다섯 run은 hash 불변이다.\n"
            "활성 측정의 실제 순서는 1 → 3 → 4 → 5 → 6 → replacement 2다. 원래 수집의 실패를 소급 취소하지 않았다.\n"
