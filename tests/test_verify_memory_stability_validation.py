    def test_full_success_independent_of_runner_codecs_measurements_preserves_bytes(self):
        before = {p: audit.digest(p.read_bytes()) for p in self.directory.rglob("*") if p.is_file()}
        forbidden = AssertionError("Audit executed prohibited producer/codec code")
        with patch.object(runner, "build_plan", side_effect=forbidden), patch.object(runner, "generate_input", side_effect=forbidden), \
                patch.object(runner, "summarize", side_effect=forbidden), patch.object(runner, "run_worker", side_effect=forbidden), \
                patch.object(runner.compressors, "compress_data", side_effect=forbidden), \
                patch.object(runner.compressors, "decompress_data", side_effect=forbidden), \
                patch.object(runner.memory_benchmark, "_worker", side_effect=forbidden):
            report = audit.audit(self.directory)
        self.assertIs(report["audit_passed"], True)
        self.assertIs(report["score_inclusion"], False)
        self.assertEqual(report["sample_count"], 84)
        self.assertEqual(report["runs"], [dict(run_id=i, reference_count=336, memory_repeat_count=3360,
                                             timing_repeat_count=3360, job_count=3696, measurement_count=336) for i in range(1, 7)])
        self.assertEqual({p: audit.digest(p.read_bytes()) for p in before}, before)
        self.assertEqual(set(report["input_sha256"]), {p.relative_to(self.directory).as_posix() for p in before})
        for n, checksum in report["input_sha256"].items():
            self.assertEqual(audit.digest((self.directory / n).read_bytes()), checksum)

