    def test_schedule_exact_boundaries(self):
        first = datetime(2026, 10, 14, 1, tzinfo=timezone.utc)
        previous = [(first, first + timedelta(minutes=15))]
        for minutes in (-60, 60):
            audit.check_schedule(3, first + timedelta(days=1, minutes=minutes), previous)
        for seconds in (-3601, 3601):
            with self.assertRaises(audit.AuditError):
                audit.check_schedule(3, first + timedelta(days=1, seconds=seconds), previous)
        for seconds in (1800, 5400):
            audit.check_schedule(2, previous[-1][1] + timedelta(seconds=seconds), previous)
        for seconds in (1799, 5401):
            with self.assertRaises(audit.AuditError):
                audit.check_schedule(2, previous[-1][1] + timedelta(seconds=seconds), previous)
        late = first.replace(hour=14, minute=50)  # Seoul 23:50
        with self.assertRaisesRegex(audit.AuditError, "another local date"):
            audit.check_schedule(2, late + timedelta(minutes=45), [(late, late + timedelta(minutes=5))])

